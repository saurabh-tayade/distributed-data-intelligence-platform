from hashlib import sha256
import importlib.metadata
import json
import os
from pathlib import Path
import re
import stat
import sys

sys.path.insert(0, str(Path(__file__).absolute().parent))
from publication_metadata import canonical_bytes
import artifact_import_verifier as capture

COMMAND_LIMIT = 65536
EVIDENCE_LIMIT = 16 * 1024**2
POLICY = 'E5_RELIABILITY_PREFLIGHT_V1'
MODULES = ('reliability_execution_preflight.py', 'artifact_import_verifier.py', 'publication_metadata.py',
           'reliability_format_inputs.py', 'reliability_format_metadata.py', 'reliability_format_parquet.py',
           'reliability_inputs.py', 'reliability_metadata.py', 'service_reference.py',
           'reliability_format_publication.py', 'reliability_format_processing.py', 'reliability_format_analytics.py')
VERSIONS = dict(java='21', python='3.12.15', pyspark='4.0.2', duckdb='1.4.5')
SPARK = dict(master='local[2]', shuffle_partitions=8, default_parallelism=8, driver_memory_mib=1024,
             executor_memory_mib=1024, output_partitions=4, event_log_enabled=False)
CODES = capture.CODES | {'RESOURCE_LIMIT', 'RUNTIME_MISMATCH', 'INPUT_INVALID'}


class Failure(Exception):
    def __init__(self, code):
        self.code = code
        super().__init__(code)


def need(value, code='INPUT_INVALID'):
    if not value:
        raise Failure(code)


def fields(n, names):
    need(type(n) is dict and set(n) == set(names))


def text(n, pattern):
    need(type(n) is str and re.fullmatch(pattern, n) is not None)
    return n


def parse(raw, limit):
    need(type(raw) is bytes and 0 < len(raw) <= limit)
    def pairs(items):
        out = {}
        for k, v in items:
            need(k not in out)
            out[k] = v
        return out
    def invalid(_):
        raise Failure('INPUT_INVALID')
    try:
        n = json.loads(raw.decode('utf-8'), object_pairs_hook=pairs, parse_float=invalid, parse_constant=invalid)
        need(canonical_bytes(n) == raw)
        return n
    except (ValueError, UnicodeError, RecursionError):
        raise Failure('INPUT_INVALID') from None


def read(path, maximum, *, private=False):
    try:
        p = Path(path)
        need(p.is_absolute() and p.resolve(strict=True) == p, 'PATH_UNSAFE')
        s = p.lstat()
        need(stat.S_ISREG(s.st_mode) and s.st_nlink == 1, 'PATH_UNSAFE')
        if private:
            need(s.st_uid == os.getuid() and s.st_mode & 0o077 == 0, 'PATH_UNSAFE')
        need(s.st_size <= maximum, 'RESOURCE_LIMIT')
        fd = os.open(p, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
        with os.fdopen(fd, 'rb') as f:
            need(capture.stamp(s) == capture.stamp(os.fstat(f.fileno())), 'EVIDENCE_CHANGED')
            raw = f.read(maximum + 1)
            need(len(raw) <= maximum, 'RESOURCE_LIMIT')
            need(capture.stamp(s) == capture.stamp(os.fstat(f.fileno())), 'EVIDENCE_CHANGED')
        need(capture.stamp(s) == capture.stamp(p.lstat()), 'EVIDENCE_CHANGED')
        return raw
    except FileNotFoundError:
        raise Failure('EVIDENCE_UNAVAILABLE') from None
    except OSError:
        raise Failure('EVIDENCE_UNAVAILABLE') from None


def deployment_manifest(revision, root):
    """Explicit provisioning/test setup helper, never called to repair an import/run."""
    text(revision, r'[0-9a-f]{40}')
    return dict(deploymentRevision=revision, versions=VERSIONS.copy(), spark=SPARK.copy(),
                modules={name: sha256(read(Path(root)/name, 1024**2)).hexdigest() for name in MODULES})


def verify_runtime(runtime):
    fields(runtime, ('profileId', 'profileSha256', 'configuration'))
    text(runtime['profileId'], r'[A-Za-z0-9_-]{1,128}')
    text(runtime['profileSha256'], r'[0-9a-f]{64}')
    c = runtime['configuration']
    need(sha256(canonical_bytes(c)).hexdigest() == runtime['profileSha256'], 'RUNTIME_MISMATCH')
    fields(c, ('executionRuntimeVersion', 'pipeline', 'runProfileId', 'runProfileSha256', 'python', 'javaHome',
               'processingRoot', 'deploymentSha256', 'deploymentRevision', 'bindings', 'verificationSeconds'))
    need(type(c['executionRuntimeVersion']) is int and c['executionRuntimeVersion'] == 1 and c['pipeline'] == 'RELIABILITY_V2', 'RUNTIME_MISMATCH')
    need(type(c['verificationSeconds']) is int and 1 <= c['verificationSeconds'] <= 900, 'RUNTIME_MISMATCH')
    root = Path(c['processingRoot'])
    need(root == Path(__file__).absolute().parent and root.resolve(strict=True) == root, 'RUNTIME_MISMATCH')
    # The manifest is provisioned with the deployment, never generated by verification.
    raw = read(root/'e5-reliability-deployment.json', 65536)
    manifest = parse(raw, 65536)
    fields(manifest, ('deploymentRevision', 'versions', 'spark', 'modules'))
    need(manifest['deploymentRevision'] == c['deploymentRevision'] and sha256(raw).hexdigest() == c['deploymentSha256'], 'RUNTIME_MISMATCH')
    text(c['deploymentRevision'], r'[0-9a-f]{40}')
    need(manifest['versions'] == VERSIONS and manifest['spark'] == SPARK, 'RUNTIME_MISMATCH')
    try:
        need(Path(c['python']).is_absolute() and Path(c['python']).samefile(sys.executable), 'RUNTIME_MISMATCH')
    except OSError:
        raise Failure('RUNTIME_MISMATCH') from None
    fields(c['bindings'], ('batch', 'reference', 'output', 'staging', 'temp', 'control'))
    for value in c['bindings'].values():
        text(value, r'[A-Za-z0-9_-]{1,128}')
    fields(manifest['modules'], MODULES)
    for name in MODULES:
        need(sha256(read(root/name, 1024**2)).hexdigest() == manifest['modules'][name], 'RUNTIME_MISMATCH')
    try:
        import duckdb
        import pyspark
    except ImportError:
        raise Failure('RUNTIME_MISMATCH') from None
    need(sys.version_info[:3] == (3, 12, 15) and duckdb.__version__ == '1.4.5' and pyspark.__version__ == '4.0.2', 'RUNTIME_MISMATCH')
    # Importing this validator invokes neither publisher nor SparkSession.
    from reliability_format_publication import validate_execution_config
    validate_execution_config(manifest['spark'])
    need('pyspark.java_gateway' not in sys.modules or not os.environ.get('PYSPARK_GATEWAY_PORT'), 'RUNTIME_MISMATCH')
    return dict(java='21', python='.'.join(map(str, sys.version_info[:3])), pyspark=pyspark.__version__, duckdb=duckdb.__version__)


def validate_command(c):
    fields(c, ('protocolVersion', 'runId', 'attemptId', 'ownerEpoch', 'stage', 'itemOrdinal', 'capturedConfigSha256',
               'checkpointId', 'runtime', 'selection', 'bundleSha256'))
    need(type(c['protocolVersion']) is int and c['protocolVersion'] == 1 and c['stage'] == 'CHECK_INPUTS' and type(c['itemOrdinal']) is int and c['itemOrdinal'] == 0)
    for key in ('runId', 'attemptId', 'checkpointId'):
        text(c[key], r'[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}')
    text(c['ownerEpoch'], r'[1-9][0-9]{0,18}')
    for key in ('capturedConfigSha256', 'bundleSha256'):
        text(c[key], r'[0-9a-f]{64}')
    need(c['selection'] == 'selection.json')


def root(binding):
    fields(binding, ('root', 'rootDevice', 'rootInode'))
    p = Path(binding['root'])
    try:
        need(p.is_absolute() and p.resolve(strict=True) == p and p.is_dir(), 'PATH_UNSAFE')
        s = p.lstat()
        need((str(s.st_dev), str(s.st_ino)) == (binding['rootDevice'], binding['rootInode']), 'EVIDENCE_CHANGED')
        return p
    except OSError:
        raise Failure('EVIDENCE_UNAVAILABLE') from None


def qualify(c, bundle):
    validate_command(c)
    fields(bundle, ('capturedSelection', 'bindings'))
    f = bundle['capturedSelection']
    need(sha256(canonical_bytes(f)).hexdigest() == c['capturedConfigSha256'])
    need(f['pipeline'] == 'RELIABILITY_V2' and f['pipelineVersion'] == 1 and f['productId'] == 'application-reliability')
    runtime = verify_runtime(c['runtime'])
    rc = c['runtime']['configuration']
    ep = f['executionProfile']
    need(rc['runProfileId'] == ep['profileId'] and rc['runProfileSha256'] == ep['configurationSha256'] and
         rc['deploymentSha256'] == ep['configuration']['runtime']['deploymentSha256'], 'RUNTIME_MISMATCH')
    need(sha256(canonical_bytes(ep['configuration'])).hexdigest() == ep['configurationSha256'])
    policy = ep['configuration']['sourceProfile']
    need(policy in ('request-jsonl-v2', 'request-parquet-v1'))
    fmt = 'JSONL' if policy == 'request-jsonl-v2' else 'PARQUET'
    bindings = bundle['bindings']
    fields(bindings, ('batch', 'reference', 'output', 'staging', 'temp', 'control'))
    roots = {role: root(b) for role, b in bindings.items()}
    expected_roles = dict(batch='BATCH', reference='REFERENCE', output='RELIABILITY', staging='STAGING', temp='TEMP', control='CONTROL')
    for role, binding in bindings.items():
        rows = [b for b in f['storageBindings'] if b['bindingId'] == rc['bindings'][role]]
        need(len(rows) == 1 and rows[0]['role'] == expected_roles[role])
        b = rows[0]
        need(sha256(canonical_bytes(b['configuration'])).hexdigest() == b['configurationSha256'])
        expected = {key:b['configuration'][key] for key in ('root', 'rootDevice', 'rootInode')}
        need(binding == expected, 'EVIDENCE_CHANGED')
    import reliability_format_metadata as m
    m.separate(*roots.values())
    # Cooperative admission only; no reservation or namespace creation.
    for role in ('output', 'staging', 'temp', 'control'):
        need(os.access(roots[role], os.W_OK | os.X_OK), 'EVIDENCE_UNAVAILABLE')
        free = os.statvfs(roots[role])
        need(free.f_bavail * free.f_frsize >= 1024**3, 'RESOURCE_LIMIT')
    sources = {}
    need(type(f['sources']) is list and 1 <= len(f['sources']) <= 32)
    for s in f['sources']:
        sc = s['configuration']
        need(s['sourceId'] not in sources and sc['dataOrigin'] == 'synthetic' and sc['profile'] == policy and sc['feedEndpointId'] is None)
        need(sha256(canonical_bytes(sc)).hexdigest() == s['configurationSha256'])
        sources[s['sourceId']] = s
    items = f['inputs']
    need(type(items) is list and 2 <= len(items) <= 33)
    batches, refs, captures, seen, batch_sources = [], [], [], set(), set()
    for item in items:
        text(item['artifactId'], r'[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}')
        need(item['artifactId'] not in seen)
        seen.add(item['artifactId'])
        qualified = item['qualification']
        need(sha256(canonical_bytes(qualified)).hexdigest() == item['evidenceSha256'] and qualified['qualificationVersion'] == 1)
        a = qualified['selection']
        need(a['productId'] == 'application-reliability')
        role = 'batch' if item['role'] == 'RELIABILITY_BATCH' else 'reference'
        need(a['storageBindingId'] == rc['bindings'][role] and item['storageBindingId'] == a['storageBindingId'])
        request = dict(protocolVersion=1, operationId=c['checkpointId'], selectionSha256=sha256(canonical_bytes(a)).hexdigest(),
                       mode='VERIFY', binding=bindings[role], artifact=a, expectedCapture=None)
        capture.validate(request)  # Existing exact namespace/version validator.
        if role == 'batch':
            need(a['kind'] == 'RELIABILITY_BATCH_V2' and a['identity']['inputFormat'] == fmt)
            i = a['identity']
            need(i['sourceId'] in sources)
            source = sources[i['sourceId']]
            need(i['sourceRevision'] == source['revision'] and i['registeredProfileSha256'] == source['configuration']['registeredProfileSha256'] and
                 a['storageBindingId'] == source['configuration']['inputStorageProfileId'])
            batches.append((i['sourceId'], i['batchId'], a['fingerprint']))
            batch_sources.add(i['sourceId'])
        else:
            need(item['role'] == 'SERVICE_REFERENCE' and a['kind'] == 'SERVICE_REFERENCE')
            refs.append(a)
        before = capture.capture(a, bindings[role], qualified['verification']['capture'])
        need(before == qualified['verification']['capture'], 'EVIDENCE_CHANGED')
        # Mandatory existing full reader, plus joint dependency verification below.
        native = capture.qualify(a, bindings[role])
        need(native == qualified['verification']['native'], 'EVIDENCE_CHANGED')
        captures.append(dict(artifactId=item['artifactId'], registeredEvidenceSha256=item['evidenceSha256'], capture=before))
    need(1 <= len(batches) <= 32 and len(refs) == 1 and batch_sources == set(sources))
    from reliability_format_inputs import verify_dependencies
    ref = refs[0]
    deps = verify_dependencies(batch_root=roots['batch'], input_format=fmt, batches=batches, reference_root=roots['reference'],
                               reference_id=ref['identity']['referenceId'], revision=ref['identity']['revision'], reference_fingerprint=ref['fingerprint'],
                               output_root=roots['output'], staging_root=roots['staging'])
    deps.check()
    for item, old in zip(items, captures, strict=True):
        a = item['qualification']['selection']
        role = 'batch' if a['kind'] == 'RELIABILITY_BATCH_V2' else 'reference'
        need(capture.capture(a, bindings[role], old['capture']) == old['capture'], 'EVIDENCE_CHANGED')
    need(verify_runtime(c['runtime']) == runtime, 'RUNTIME_MISMATCH')
    files = [file for b in deps.batches for file in b.manifest['files']]
    counts = dict(files=str(len(files)), bytes=str(sum(file['byte_length'] for file in files)), rows=str(sum(file['record_count'] for file in files)))
    return dict(evidenceVersion=1, policy=POLICY, runId=c['runId'], attemptId=c['attemptId'], ownerEpoch=c['ownerEpoch'],
                checkpointId=c['checkpointId'], capturedConfigSha256=c['capturedConfigSha256'], runtimeProfileId=c['runtime']['profileId'],
                runtimeProfileSha256=c['runtime']['profileSha256'], deploymentSha256=rc['deploymentSha256'], runtime=runtime,
                inputFormat=fmt, nativeDependencyFingerprint=deps.fingerprint, nativeDependencies=deps.manifest(),
                artifacts=sorted(captures, key=lambda n:n['artifactId']), counts=counts)


def write_new(path, raw, limit):
    need(len(raw) <= limit, 'RESOURCE_LIMIT')
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, 'wb') as f:
            f.write(raw)
            f.flush()
            os.fsync(f.fileno())
        need(read(path, limit, private=True) == raw, 'EVIDENCE_CHANGED')
    except OSError:
        raise Failure('EVIDENCE_UNAVAILABLE') from None


def recheck(c, bundle, expected):
    """Read-only C2b seam: requalify the same pinned selection; never trust the stage flag alone."""
    current = qualify(c, bundle)
    need(current == expected, 'EVIDENCE_CHANGED')
    return current


def main(argv=None):
    c = None
    try:
        args = sys.argv[1:] if argv is None else argv
        need(len(args) == 1)
        command = Path(args[0])
        raw = read(command, COMMAND_LIMIT, private=True)
        c = parse(raw, COMMAND_LIMIT)
        validate_command(c)
        bundle_raw = read(command.parent/'selection.json', EVIDENCE_LIMIT, private=True)
        need(sha256(bundle_raw).hexdigest() == c['bundleSha256'], 'EVIDENCE_CHANGED')
        evidence = qualify(c, parse(bundle_raw, EVIDENCE_LIMIT))
        write_new(command.parent/'evidence.json', canonical_bytes(evidence), EVIDENCE_LIMIT)
        result = dict(protocolVersion=1, runId=c['runId'], attemptId=c['attemptId'], stage='CHECK_INPUTS', itemOrdinal=0,
                      status='OK', code=None, evidenceId=c['checkpointId'], counts=evidence['counts'])
        write_new(command.parent/'result.json', canonical_bytes(result), COMMAND_LIMIT)
        return 0
    except Exception as error:
        code = getattr(error, 'code', 'INPUT_INVALID')
        if code not in CODES:
            code = 'INPUT_INVALID'
        if c is not None:
            try:
                validate_command(c)
                result = dict(protocolVersion=1, runId=c['runId'], attemptId=c['attemptId'], stage='CHECK_INPUTS', itemOrdinal=0,
                              status='FAILED', code=code, evidenceId=None, counts={})
                write_new(command.parent/'result.json', canonical_bytes(result), COMMAND_LIMIT)
            except Exception:
                pass
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
